import assert from "node:assert/strict";
import { ConvexHttpClient } from "convex/browser";
import { makeFunctionReference } from "convex/server";

const url = process.env.EXPO_PUBLIC_CONVEX_URL;
assert.equal(url, "https://content-salmon-941.convex.cloud", "This proof only writes to the approved cloud DEV deployment.");
const ref = makeFunctionReference;
async function guest() {
  const client = new ConvexHttpClient(url);
  const session = await client.action(ref("auth:signIn"), { provider: "anonymous" });
  assert.ok(session.tokens?.token);
  client.setAuth(session.tokens.token);
  return { client, token: session.tokens.token };
}
const [{ client: viewer, token }, { client: friend }, { client: stranger }] = await Promise.all([guest(), guest(), guest()]);
const day = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Los_Angeles", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
const start = new Date(`${day}T12:00:00Z`);
start.setUTCDate(start.getUTCDate() - 6);
const window = { weekStart: start.toISOString().slice(0, 10), weekEnd: day };
const topic = { scope: null, title: "Wheel-thrown mugs", summary: "I want to make my own coffee mug on the wheel.", tags: ["wheel throwing"], source: "manual", date: null, ...window, audience: "friends", importKey: "dev-proof-mug" };
const id = await viewer.mutation(ref("topics:add"), topic);
assert.equal(await viewer.mutation(ref("topics:add"), topic), id);
const fresh = new ConvexHttpClient(url);
fresh.setAuth(token);
assert.equal((await fresh.query(ref("topics:listMine"), {})).filter(row => row._id === id).length, 1);
console.log("PASS fresh authenticated read and idempotent retry: exactly one topic");
await friend.mutation(ref("topics:add"), { ...topic, title: "Saturday ceramics", summary: "I’m looking for a Saturday ceramics class.", tags: ["ceramics"], importKey: "dev-proof-class" });
const { code } = await viewer.mutation(ref("friendships:createInvite"), {});
const relationship = await friend.mutation(ref("friendships:request"), { code });
assert.equal(await friend.query(ref("topics:get"), { id }), null);
await viewer.mutation(ref("friendships:accept"), { id: relationship });
assert.equal((await friend.query(ref("topics:get"), { id })).title, topic.title);
assert.equal(await stranger.query(ref("topics:get"), { id }), null);
const mine = await viewer.query(ref("profiles:mine"), {});
assert.equal(await stranger.query(ref("profiles:get"), { userId: mine.userId }), null);
assert.equal((await viewer.query(ref("feed:matches"), window))[0].sharedTags[0], "pottery");
assert.equal((await stranger.query(ref("feed:list"), window)).length, 0);
console.log("PASS mutual acceptance, shared detail, stranger isolation and pottery synonyms");
await viewer.mutation(ref("topics:update"), { id, audience: "private" });
assert.equal(await friend.query(ref("topics:get"), { id }), null);
assert.equal((await viewer.query(ref("feed:matches"), window)).length, 0);
console.log("PASS unshare removes detail and overlap");
await viewer.mutation(ref("topics:update"), { id, audience: "friends" });
await viewer.mutation(ref("profiles:update"), { sharingPaused: true, scope: null });
assert.equal(await friend.query(ref("topics:get"), { id }), null);
assert.equal((await viewer.query(ref("feed:matches"), window)).length, 0);
await viewer.mutation(ref("profiles:update"), { sharingPaused: false, scope: null });
await viewer.mutation(ref("friendships:remove"), { id: relationship });
assert.equal(await friend.query(ref("topics:get"), { id }), null);
assert.equal((await viewer.query(ref("feed:matches"), window)).length, 0);
await viewer.mutation(ref("topics:remove"), { id });
console.log("PASS pause and friend removal immediately remove visibility and matches");
const credential = { email: `${crypto.randomUUID()}@installation.satsuma.invalid`, password: crypto.randomUUID() + crypto.randomUUID() };
const installation = new ConvexHttpClient(url);
const enrolled = await installation.action(ref("auth:signIn"), { provider: "installation", params: { ...credential, flow: "signUp" } });
installation.setAuth(enrolled.tokens.token);
const identity = (await installation.query(ref("profiles:mine"), {})).userId;
const durableId = await installation.mutation(ref("topics:add"), { ...topic, importKey: "installation-recovery" });
await installation.action(ref("auth:signOut"), {});
const recovered = new ConvexHttpClient(url);
const restored = await recovered.action(ref("auth:signIn"), { provider: "installation", params: { ...credential, flow: "signIn" } });
recovered.setAuth(restored.tokens.token);
assert.equal((await recovered.query(ref("profiles:mine"), {})).userId, identity);
assert.equal((await recovered.query(ref("topics:listMine"), {}))[0]._id, durableId);
await recovered.mutation(ref("topics:remove"), { id: durableId });
console.log("PASS installation credential recovers the same owner and topics after session revocation");
const retryPayload = { ...topic, importKey: "preserve-later-privacy" };
const retryId = await recovered.mutation(ref("topics:add"), retryPayload);
await recovered.mutation(ref("topics:update"), { id: retryId, title: "My later edit", audience: "private" });
assert.equal(await recovered.mutation(ref("topics:add"), retryPayload), retryId);
const preserved = await recovered.query(ref("topics:get"), { id: retryId });
assert.equal(preserved.title, "My later edit");
assert.equal(preserved.audience, "private");
await recovered.mutation(ref("topics:remove"), { id: retryId });
assert.equal(await recovered.mutation(ref("topics:add"), retryPayload), retryId);
assert.equal(await recovered.query(ref("topics:get"), { id: retryId }), null);
console.log("PASS create-once import retry preserves later edits, unsharing and deletion");
